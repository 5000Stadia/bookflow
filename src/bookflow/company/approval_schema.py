"""Revision-bound bill approval evidence; no approval row is a financial document."""
import sqlalchemy as sa


def define_tables(metadata, C, T, common):
    policies = T('approval_policies', *common(),
        C('target', sa.String(24), 'Approval target.', nullable=False),
        C('state', sa.String(16), 'draft or published.', nullable=False),
        C('definition', sa.Text, 'Simple Review step and enabled switch JSON.', nullable=False),
        description='Versioned policy headers. Publication captures an immutable revision.')
    policy_revisions = T('approval_policy_revisions',
        C('id', sa.String(26), 'Policy revision identity.', primary_key=True),
        C('publication_sequence', sa.Integer, 'Monotone publication order independent of wall-clock changes.', nullable=False, unique=True),
        C('policy_id', sa.String(26), 'Policy header.', sa.ForeignKey('approval_policies.id', ondelete='RESTRICT'), nullable=False),
        C('version', sa.Integer, 'Published policy version.', nullable=False),
        C('definition', sa.Text, 'Captured policy definition JSON.', nullable=False),
        C('created_at', sa.String(32), 'Publication time.', nullable=False),
        sa.UniqueConstraint('policy_id', 'version'),
        description='Immutable published simple bill policies.')
    requests = T('approval_requests',
        C('id', sa.String(26), 'Approval request identity.', primary_key=True),
        C('draft_id', sa.String(26), 'Submitted draft.', sa.ForeignKey('purchase_drafts.id', ondelete='RESTRICT'), nullable=False),
        C('draft_version', sa.Integer, 'Frozen submitted revision.', nullable=False),
        C('policy_revision_id', sa.String(26), 'Captured published policy.', sa.ForeignKey('approval_policy_revisions.id', ondelete='RESTRICT'), nullable=False),
        C('steps', sa.Text, 'Captured ordered steps JSON.', nullable=False),
        C('requesters', sa.Text, 'Creator and submitter actor and effective principal IDs JSON.', nullable=False),
        C('state', sa.String(16), 'pending, approved, rejected, withdrawn or committed.', nullable=False),
        C('version', sa.Integer, 'Expected request version.', nullable=False),
        C('current_step', sa.Integer, 'Zero-based Review step index.', nullable=False),
        C('created_at', sa.String(32), 'Submission time.', nullable=False),
        sa.UniqueConstraint('draft_id', 'draft_version'),
        sa.Index('ix_approval_requests_state', 'state', 'id'),
        description='Revision-bound approval requests with captured policy assignments.')
    events = T('approval_events',
        C('id', sa.String(26), 'Approval event identity.', primary_key=True),
        C('request_id', sa.String(26), 'Request, when submitted.', sa.ForeignKey('approval_requests.id', ondelete='RESTRICT')),
        C('draft_id', sa.String(26), 'Draft evidence belongs to.', sa.ForeignKey('purchase_drafts.id', ondelete='RESTRICT'), nullable=False),
        C('sequence', sa.Integer, 'Increasing per-draft event order.', nullable=False),
        C('action', sa.String(32), 'Submission, decision, invalidation, commit or inverse.', nullable=False),
        C('actor', sa.String(26), 'Acting member.', nullable=False),
        C('principal', sa.String(26), 'Bound principal.'),
        C('interface', sa.String(16), 'Calling interface.', nullable=False),
        C('reason', sa.String(140), 'Required reason.', nullable=False),
        C('created_at', sa.String(32), 'UTC event time.', nullable=False),
        C('data', sa.Text, 'Exact act details JSON.', nullable=False),
        sa.UniqueConstraint('draft_id', 'sequence'),
        description='Append-only attributed approval events and invalidations.')
    commits = T('approval_commits',
        C('id', sa.String(26), 'Unique commit attempt.', primary_key=True),
        C('request_id', sa.String(26), 'Captured approval request, absent for layer-off drafts.', sa.ForeignKey('approval_requests.id', ondelete='RESTRICT')),
        C('draft_id', sa.String(26), 'Producing draft.', sa.ForeignKey('purchase_drafts.id', ondelete='RESTRICT'), nullable=False),
        C('draft_version', sa.Integer, 'Committed draft revision.', nullable=False),
        C('document_id', sa.String(26), 'Native bill.', sa.ForeignKey('transactions.id', ondelete='RESTRICT'), nullable=False),
        C('document_version', sa.Integer, 'Produced native version.', nullable=False),
        C('operation', sa.String(16), 'create or correct.', nullable=False),
        C('batch_id', sa.String(26), 'Reversible unit.', sa.ForeignKey('batches.id', ondelete='RESTRICT'), nullable=False, unique=True),
        C('before_snapshot', sa.Text, 'Captured prior native commercial snapshot for exact inverse validation.'),
        C('before_payload', sa.Text, 'Exact prior correction payload JSON.'),
        C('created_at', sa.String(32), 'Commit time.', nullable=False),
        description='Immutable native producing operations and their reversible batches.')
    receipts = T('approval_operations',
        C('id', sa.String(26), 'Permanent operation receipt.', primary_key=True),
        C('command', sa.String(64), 'Shared command name.', nullable=False),
        C('actor', sa.String(26), 'Operation key owner.', nullable=False),
        C('operation_key', sa.String(128), 'Permanent caller operation key.', nullable=False),
        C('request', sa.Text, 'Canonical input, reason and principal JSON.', nullable=False),
        C('result', sa.Text, 'Exact original command result JSON.', nullable=False),
        sa.UniqueConstraint('command', 'actor', 'operation_key'),
        description='Permanent approval retry receipts; authorization is checked before replay.')
    return {t.name: t for t in (policies, policy_revisions, requests, events, commits, receipts)}
