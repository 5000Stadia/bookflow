"""Lead-owned contacts and identity; optional CRM layers remain off."""
import sqlalchemy as sa


def define_tables(c):
    C, T = c._column, c._table
    leads = T('crm_leads', *c._common(),
        C('display_name', sa.String(200), 'Lead display name; duplicate names are permitted.', nullable=False),
        C('name_key', sa.String(400), 'Normalized case-folded name used for exact selectors.', nullable=False),
        C('company_name', sa.String(200), 'Optional business name.', nullable=True),
        *c._person_identity(), *c._record_address('address', 'Lead postal address'),
        C('owner_id', sa.String(26), 'Responsible company member; ownership grants no authority.', nullable=True),
        C('source', sa.String(500), 'Where the enquiry came from.', nullable=True),
        C('rating', sa.String(8), 'unrated, cold, warm or hot.', nullable=False),
        C('summary', sa.Text, 'Short internal summary, separate from attributed notes.', nullable=True),
        C('status', sa.String(10), 'Lifecycle: open, closed or converted.', nullable=False),
        C('close_reason', sa.String(1000), 'Reason for closing; null while open.', nullable=True),
        C('archived', sa.Boolean, 'Hidden from ordinary lists without deleting history.', nullable=False),
        C('duplicate_of', sa.String(26), 'Explicit same-company duplicate lead; never an automatic merge.', sa.ForeignKey('crm_leads.id', ondelete='RESTRICT'), nullable=True),
        sa.CheckConstraint("length(trim(display_name)) > 0", name='ck_crm_lead_name'),
        sa.CheckConstraint("rating IN ('unrated','cold','warm','hot')", name='ck_crm_lead_rating'),
        sa.CheckConstraint("status IN ('open','closed','converted')", name='ck_crm_lead_status'),
        sa.CheckConstraint("status != 'closed' OR length(trim(close_reason)) > 0", name='ck_crm_lead_close'),
        sa.CheckConstraint('duplicate_of IS NULL OR duplicate_of != id', name='ck_crm_lead_duplicate'),
        sa.Index('ix_crm_leads_lifecycle_owner_name', 'status', 'archived', 'owner_id', 'name_key'),
        sa.Index('ix_crm_leads_name', 'name_key', 'id'),
        description='Prospects separate from accounting customers; no balances or ledger effects.')
    contacts = T('crm_lead_contacts', *c._owned_child('lead_id', 'crm_leads'), *c._contact_columns(),
        sa.CheckConstraint("role IN ('primary','alternate','additional')", name='ck_crm_lead_contacts_role'),
        sa.Index('ux_crm_lead_contacts_primary', 'lead_id', unique=True, sqlite_where=sa.text("active = 1 AND role = 'primary'")),
        sa.Index('ux_crm_lead_contacts_alternate', 'lead_id', unique=True, sqlite_where=sa.text("active = 1 AND role = 'alternate'")),
        description='Stable ordered contacts owned and versioned by a lead.')
    points = T('crm_lead_contact_points', *c._owned_child('contact_id', 'crm_lead_contacts'), *c._contact_point_columns(),
        description='Stable typed contact points owned through a lead contact.')
    conversions = T('crm_conversions',
        C('id', sa.String(26), 'Stable ULID of this conversion.', primary_key=True),
        C('lead_id', sa.String(26), 'Converted lead.', sa.ForeignKey('crm_leads.id', ondelete='RESTRICT'), nullable=False),
        C('customer_id', sa.String(26), 'Top-level customer the lead became or was linked to.',
          sa.ForeignKey('customers.id', ondelete='RESTRICT'), nullable=False),
        C('target', sa.String(8), 'new: a customer this conversion created; existing: an existing customer.', nullable=False),
        C('batch_id', sa.String(26), 'The reversible batch that holds this conversion.',
          sa.ForeignKey('batches.id', ondelete='RESTRICT'), nullable=False, unique=True),
        C('request_hash', sa.String(64), 'Digest of the request, so an identical retry returns this receipt.', nullable=False),
        C('lead_version_before', sa.Integer, 'Lead version the conversion expected.', nullable=False),
        C('lead_version_after', sa.Integer, 'Lead version the conversion left.', nullable=False),
        C('lead_status_before', sa.String(10), 'Lifecycle restored by reversal.', nullable=False),
        C('lead_close_reason_before', sa.String(1000), 'Close reason restored by reversal; null when open.', nullable=True),
        C('customer_version_before', sa.Integer, 'Existing customer version expected; null for a new customer.', nullable=True),
        C('customer_version_after', sa.Integer, 'Customer version the conversion left.', nullable=False),
        C('lead_label', sa.String(200), 'Lead display name captured at conversion.', nullable=False),
        C('customer_label', sa.String(400), 'Customer name captured at conversion.', nullable=False),
        C('state', sa.String(10), 'active or reversed.', nullable=False),
        C('created_at', sa.String(32), 'UTC time of the conversion.', nullable=False),
        C('created_by', sa.String(26), 'Principal that converted the lead.', nullable=False),
        C('created_via', sa.String(16), 'Interface used.', nullable=False),
        C('reversed_at', sa.String(32), 'UTC time the conversion was reversed; null while active.', nullable=True),
        C('reversed_by', sa.String(26), 'Principal that reversed it; null while active.', nullable=True),
        C('reversal_batch_id', sa.String(26), 'Reversal batch; null while active.',
          sa.ForeignKey('batches.id', ondelete='RESTRICT'), nullable=True),
        sa.CheckConstraint("target IN ('new','existing')", name='ck_crm_conversion_target'),
        sa.CheckConstraint("state IN ('active','reversed')", name='ck_crm_conversion_state'),
        sa.CheckConstraint("(state = 'reversed') = (reversed_at IS NOT NULL)", name='ck_crm_conversion_reversed'),
        sa.Index('ux_crm_conversions_active_lead', 'lead_id', unique=True, sqlite_where=sa.text("state = 'active'")),
        sa.Index('ix_crm_conversions_customer', 'customer_id', 'state', 'created_at'),
        description='Lead-to-customer links, each a reversible batch; reversed links remain as history.')
    mappings = T('crm_conversion_contacts',
        C('id', sa.String(26), 'Stable ULID of this mapping.', primary_key=True),
        C('conversion_id', sa.String(26), 'Conversion this mapping belongs to.',
          sa.ForeignKey('crm_conversions.id', ondelete='RESTRICT'), nullable=False),
        C('lead_contact_id', sa.String(26), 'Lead contact copied from.',
          sa.ForeignKey('crm_lead_contacts.id', ondelete='RESTRICT'), nullable=False),
        C('customer_contact_id', sa.String(26), 'Customer contact written.',
          sa.ForeignKey('customer_contacts.id', ondelete='RESTRICT'), nullable=False),
        C('action', sa.String(8), 'created: a new customer contact; updated: explicit fields copied onto an existing one.', nullable=False),
        C('fields', sa.Text, 'JSON list of copied field names.', nullable=False),
        C('before', sa.Text, 'JSON of the replaced field values of an updated contact; null when created.', nullable=True),
        sa.CheckConstraint("action IN ('created','updated')", name='ck_crm_conversion_contact_action'),
        sa.Index('ix_crm_conversion_contacts_conversion', 'conversion_id', 'lead_contact_id'),
        description='Which customer contact each lead contact became; retained after reversal.')
    keys = T('crm_lead_import_keys',
        C('id', sa.String(26), 'Stable ULID of this key.', primary_key=True),
        C('source', sa.String(200), 'Import source identity (a file or list name) chosen by the importer.', nullable=False),
        C('source_key', sa.String(200), "The row's stable key within its source.", nullable=False),
        C('payload_hash', sa.String(64), 'Digest of the row as imported; a changed row with the same key refuses.', nullable=False),
        C('lead_id', sa.String(26), 'Lead the row created.', sa.ForeignKey('crm_leads.id', ondelete='RESTRICT'), nullable=False),
        C('batch_id', sa.String(26), 'Import batch.', sa.ForeignKey('batches.id', ondelete='RESTRICT'), nullable=False),
        C('created_at', sa.String(32), 'UTC time the row landed.', nullable=False),
        C('released_by', sa.String(26), 'Reversal batch that released the key; null while held.',
          sa.ForeignKey('batches.id', ondelete='RESTRICT'), nullable=True),
        C('released_at', sa.String(32), 'UTC time the key was released; null while held.', nullable=True),
        sa.Index('ux_crm_lead_import_keys_live', 'source', 'source_key', unique=True,
                 sqlite_where=sa.text('released_by IS NULL')),
        sa.Index('ix_crm_lead_import_keys_lead', 'lead_id'),
        description='Source keys of imported leads, so a repeated import does not duplicate a lead.')
    return dict(crm_leads=leads, crm_lead_contacts=contacts, crm_lead_contact_points=points,
                crm_conversions=conversions, crm_conversion_contacts=mappings, crm_lead_import_keys=keys)
